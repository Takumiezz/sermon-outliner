BibleData.getBook = function(id) { return this.books.find(b=>b.id===id); };
BibleData.findBook = function(q) { return this.books.filter(b=>b.name.includes(q)||b.abbr===q); };
BibleData.getChapterCount = function(id) { return (this.getBook(id)||{}).chapters?.length||0; };
BibleData.getGenre = function(id) { return (this.getBook(id)||{}).genre||'叙事'; };
BibleData.parseReference = function(ref) {
  var m = ref.match(/^([\u4e00-\u9fa5\u7c9f]{2,4}[记书福音]?)(\d+):(\d+)(?:-(\d+))?$/);
  if (!m) return null;
  var book = this.books.find(function(b){return b.name===m[1]||b.abbr===m[1];});
  if (!book) return null;
  return {bookId:book.id,book:book,chapter:+m[2],startVerse:+m[3],endVerse:m[4]?+m[4]:+m[3]};
};
